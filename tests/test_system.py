"""
System tests + case-study report.

    python -m tests.test_system      (or: pytest tests/)

Checks basic sanity properties and writes reports/case_studies.md
(persona -> risk profile -> top plans) for the project report.
"""
from src.recommend import recommend
from src.risk import assess

BASE = dict(age=45, sex="male", height_cm=172, weight_kg=72, smoked_100_cigarettes=False, heavy_alcohol=False,
            physically_active=True, fruit_daily=True, vegetables_daily=True, sleep_hours=7, general_health=2,
            poor_physical_health_days=0, poor_mental_health_days=0, difficulty_walking=False, high_bp="no",
            high_chol="no", diabetes="no", heart_disease=False, stroke=False, asthma=False, kidney_disease=False,
            skin_cancer=False)

PERSONAS = {
    "Healthy 25-year-old": (dict(BASE, age=25, general_health=1), {}),
    "45-year-old smoker, overweight, inactive, never checked BP/sugar":
        (dict(BASE, smoked_100_cigarettes=True, weight_kg=92, physically_active=False, fruit_daily=False,
              general_health=3, high_bp="unknown", high_chol="unknown", diabetes="unknown"), {}),
    "52-year-old with diabetes and high BP": (dict(BASE, age=52, weight_kg=85, diabetes="yes", high_bp="yes",
                                                   general_health=3), {}),
    "58-year-old with heart disease, wants protection":
        (dict(BASE, age=58, heart_disease=True, high_bp="yes", general_health=4), {"risk_tolerance": "low"}),
    "68-year-old with diabetes": (dict(BASE, age=68, diabetes="yes", general_health=4), {}),
    "35-year-old with Rs 5L employer cover": (dict(BASE, age=35), {"existing_cover_inr": 500000}),
}


def test_risk_increases_with_unhealthy_habits():
    healthy = assess(BASE, with_drivers=False)["conditions"]
    unhealthy = assess(dict(BASE, smoked_100_cigarettes=True, weight_kg=100, physically_active=False),
                       with_drivers=False)["conditions"]
    for c in ["diabetes", "high_bp", "heart_disease"]:
        assert unhealthy[c]["probability"] > healthy[c]["probability"], c


def test_risk_increases_with_age():
    young = assess(dict(BASE, age=25), with_drivers=False)["conditions"]
    old = assess(dict(BASE, age=70), with_drivers=False)["conditions"]
    for c in ["diabetes", "high_bp", "heart_disease", "stroke"]:
        assert old[c]["probability"] > young[c]["probability"], c


def test_declared_condition_is_certain():
    r = assess(dict(BASE, diabetes="yes"), with_drivers=False)["conditions"]
    assert r["diabetes"]["status"] == "declared" and r["diabetes"]["probability"] == 1.0


def test_probabilities_valid():
    for q, _ in PERSONAS.values():
        for c in assess(q, with_drivers=False)["conditions"].values():
            assert 0.0 <= c["probability"] <= 1.0


def test_eligibility_rules():
    r = recommend(dict(BASE, age=68), {})
    names = [p["plan_id"] for p in r["all_eligible_plans"]]
    assert names == ["P10"], names                      # only the senior plan accepts a 68-year-old
    r = recommend(BASE, {"annual_budget_inr": 9000})
    assert all(p["premium_year1"] <= 9000 for p in r["all_eligible_plans"])


def test_ranking_sorted_and_deterministic():
    a = recommend(BASE, {})
    b = recommend(BASE, {})
    scores = [p["score"] for p in a["all_eligible_plans"]]
    assert scores == sorted(scores)
    assert [p["plan_id"] for p in a["all_eligible_plans"]] == [p["plan_id"] for p in b["all_eligible_plans"]]


def write_case_studies():
    from src.features import ROOT
    lines = ["# Case studies", "", "Generated by `python -m tests.test_system`. Horizon 5 years, 20,000 simulations.", ""]
    for name, (q, prefs) in PERSONAS.items():
        r = recommend(q, prefs)
        lines += [f"## {name}", "", "| Condition | Status | Probability |", "|---|---|---|"]
        for c in r["risk"]["conditions"].values():
            lines.append(f"| {c['label']} | {c['status']} | {100 * c['probability']:.1f}% |")
        lines += ["", f"Expected medical bills over 5 years: Rs {r['expected_medical_bills_total']:,.0f}", "",
                  "| Rank | Plan | Premium yr 1 | Expected total | Bad case (worst 5%) |", "|---|---|---|---|---|"]
        for p in r["all_eligible_plans"][:3]:
            lines.append(f"| {p['rank']} | {p['plan_name']} | Rs {p['premium_year1']:,.0f} | "
                         f"Rs {p['expected_total_cost']:,.0f} | Rs {p['cvar95_total_cost']:,.0f} |")
        if r["recommendations"]:
            lines += ["", "Notes on top plan: " + " ".join(r["recommendations"][0]["notes"] or ["-"])]
        lines.append("")
    (ROOT / "reports" / "case_studies.md").write_text("\n".join(lines))


if __name__ == "__main__":
    tests = [v for k, v in dict(globals()).items() if k.startswith("test_")]
    for t in tests:
        t()
        print("PASS", t.__name__)
    write_case_studies()
    print("Wrote reports/case_studies.md")
